#!/usr/bin/env python3
"""Compare shared-service extraction with a preserved compiler, without timing."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', type=Path, required=True)
    parser.add_argument('--exe', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    compilers = (args.reference.resolve(), args.exe.resolve())
    native = [ROOT / 'test' / name for name in (
        'codegen/cycle_static_stacks.goose', 'codegen/cycle_scratch_locals.goose',
        'codegen/temporary_stack_base.goose', 'codegen/defer_exits.goose',
        'codegen/defer_return_from.goose', 'codegen/pad_only_layouts.goose',
        'codegen/copy_slot_layouts.goose', 'codegen/limited_array_adaptation.goose',
        'codegen/adt_field_tags.goose', 'codegen/varint_elements.goose',
        'storage/serialize.goose', 'storage/serialize_adt_tail.goose',
        'storage/self_relative_adt_payloads.goose', 'storage/relative_named_results.goose',
        'storage/resizable_adt_payload_links.goose', 'threads/thread_spawn_stack.goose',
        'runtime/stack_stats.goose',
    )]
    wasm = sorted((ROOT / 'test' / 'wasm').glob('*.goose'))
    records = []
    for target, sources in (('native', native), ('wasm', wasm)):
        for source in sources:
            for opt in (0, 2):
                outputs, diagnostics = [], []
                for label, compiler in zip(('reference', 'candidate'), compilers):
                    prefix = args.out / f'{source.stem}-{target}-O{opt}-{label}'
                    output = prefix.with_suffix('.c' if target == 'native' else '.wasm')
                    command = [str(compiler), f'-O{opt}', '-o', str(output)]
                    command += ['--standalone', '--stacks'] if target == 'native' else ['--target', 'wasm']
                    command += [str(source)]
                    result = subprocess.run(command, cwd=ROOT, capture_output=True, timeout=90)
                    prefix.with_suffix('.stdout').write_bytes(result.stdout)
                    prefix.with_suffix('.stderr').write_bytes(result.stderr)
                    prefix.with_suffix('.exit').write_text(str(result.returncode) + '\n')
                    assert result.returncode == 0, (source, target, opt, label, result.stderr)
                    outputs.append(output)
                    diagnostics.append((result.stdout, result.stderr))
                assert diagnostics[0] == diagnostics[1], (source, target, opt, 'diagnostics or stack report differ')
                assert outputs[0].read_bytes() == outputs[1].read_bytes(), (source, target, opt, 'generated bytes differ')
                records.append({'source': str(source.relative_to(ROOT)), 'source_sha256': sha(source),
                                'target': target, 'optimization': opt, 'output_sha256': sha(outputs[0])})
    manifest = {'reference_sha256': sha(compilers[0]), 'candidate_sha256': sha(compilers[1]),
                'comparisons': records}
    (args.out / 'summary.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'shared backend services: {len(records)} exact output and diagnostic comparisons passed')


if __name__ == '__main__':
    main()
